"""Generate the home page's pulse animation: a short pulse through the logo's
add-drop ring.

Writes ``overrides/partials/hero_pulse.html`` (the light, as SVG paths) and
``docs/assets/hero-pulse.css`` (their keyframes). Re-run after changing a
number here:

    python docs/make_hero_pulse.py

The physics, for a pulse shorter than a ring round trip (so it never
overlaps itself and resonance plays no part):

- every pulse moves at one group velocity, in the buses and the ring alike;
- at each coupler a fraction ``KAPPA2`` of a pulse's energy crosses to the
  other guide and the rest carries on;
- so the input splits 0.7 / 0.3 at the top coupler, and the ring's pulse
  then loses 30 % at every coupler it passes: half a round trip later a
  pulse leaves the drop port (heading left), a full round trip later one
  leaves the through port (heading right), each weaker than the last.

Brightness is the pulse's field amplitude, the square root of its energy,
relative to the input. The device geometry matches overrides/home.html:
ring radius 96, buses at y = +-123 from x = -250 to 250, couplers at x = 0.
"""
from __future__ import annotations

import math
from pathlib import Path

KAPPA2 = 0.3            # power coupled across at each coupler
V = 420.0               # group velocity, grid units per second
PULSE = 34.0            # pulse length, grid units
START = 0.4             # s, when the pulse enters at the input port
CYCLE = 11.0            # s, the animation repeats after this
HALF_TRIPS = 8          # ring half round trips drawn (the rest is too faint)
R, BUS_X = 96.0, 250.0

ROOT = Path(__file__).resolve().parent.parent
HALF = math.pi * R      # half a ring round trip, grid units


def keyframes(name: str, length: float, t0: float, opacity: list[tuple[float, float]]) -> str:
    """A dash of PULSE units running along a path of ``length`` from t0,
    with its opacity set to ``a`` from path distance ``s`` onwards for each
    ``(s, a)``. Distances are converted to times at V."""
    def pct(t: float) -> float:
        return 100.0 * t / CYCLE

    def offset(s: float) -> float:   # dash head at path distance s
        return PULSE - s

    t_end = t0 + (length + PULSE) / V
    assert t_end < CYCLE, f"{name} runs past the cycle"
    frames = [(0.0, offset(0), 0.0), (pct(t0), offset(0), opacity[0][1])]
    for (s, a), (s_next, _) in zip(opacity, opacity[1:] + [(length + PULSE, 0)]):
        if s > 0:
            frames.append((pct(t0 + s / V) - 0.001, offset(s), prev))
            frames.append((pct(t0 + s / V), offset(s), a))
        prev = a
    frames.append((pct(t_end), offset(length + PULSE), prev))
    frames.append((min(100.0, pct(t_end) + 0.001), offset(length + PULSE), 0.0))
    frames.append((100.0, offset(length + PULSE), 0.0))
    body = "\n".join(f"  {p:.3f}% {{ stroke-dashoffset: {o:.1f}; opacity: {a:.3f}; }}" for p, o, a in frames)
    return f"@keyframes {name} {{\n{body}\n}}"


def main() -> None:
    k2, t2 = KAPPA2, 1.0 - KAPPA2
    amp = math.sqrt
    t_c = START + BUS_X / V                     # head reaches the top coupler
    h = HALF / V                                 # half a round trip, in s

    paths, css = [], []

    def pulse(cls: str, d: str, length: float, t0: float, opacity) -> None:
        paths.append(f'<path class="phi-pulse {cls}" d="{d}"/>')
        css.append(f".{cls} {{ stroke-dasharray: {PULSE} {length + 2 * PULSE:.0f}; "
                   f"animation-name: {cls}; }}")
        css.append(keyframes(cls, length, t0, opacity))

    # In, then on through the top coupler: 1, then 0.7 of the energy.
    pulse("phi-p-in", f"M{-BUS_X} -123H{BUS_X}", 2 * BUS_X, START,
          [(0.0, 1.0), (BUS_X, amp(t2))])

    # The ring: 0.3 for the first half trip, then x0.7 at each coupler.
    ring_d = f"M0 {-R:g}" + "".join(
        f"A{R:g} {R:g} 0 0 1 0 {R if i % 2 == 0 else -R:g}" for i in range(HALF_TRIPS))
    energy, steps = k2, []
    for i in range(HALF_TRIPS):
        steps.append((i * HALF, amp(energy)))
        energy *= t2
    pulse("phi-p-ring", ring_d, HALF_TRIPS * HALF, t_c, steps)

    # Out-coupled pulses: drop at odd half trips, through at even ones.
    energy = k2
    for i in range(1, HALF_TRIPS + 1):
        out = energy * k2
        energy *= t2
        t0 = t_c + i * h
        if i % 2:   # bottom coupler: leaves the drop port, heading left
            pulse(f"phi-p-drop{i}", f"M0 123H{-BUS_X}", BUS_X, t0, [(0.0, amp(out))])
        else:       # top coupler: leaves the through port, heading right
            pulse(f"phi-p-thru{i}", f"M0 -123H{BUS_X}", BUS_X, t0, [(0.0, amp(out))])

    partial = ROOT / "overrides" / "partials" / "hero_pulse.html"
    partial.parent.mkdir(parents=True, exist_ok=True)
    partial.write_text(
        "{#- Generated by docs/make_hero_pulse.py; edit that, not this. -#}\n"
        + "\n".join(paths) + "\n")
    (ROOT / "docs" / "assets" / "hero-pulse.css").write_text(
        "/* Generated by docs/make_hero_pulse.py; edit that, not this. */\n"
        f"/* kappa^2 = {KAPPA2}, v = {V} units/s, cycle {CYCLE} s. */\n"
        "@media (prefers-reduced-motion: no-preference) {\n"
        f".phi-pulse {{ animation-duration: {CYCLE}s; animation-timing-function: linear;"
        " animation-iteration-count: infinite; }\n"
        + "\n".join(c for c in css if not c.startswith("@keyframes")) + "\n}\n"
        + "\n".join(c for c in css if c.startswith("@keyframes")) + "\n")
    print(f"wrote {partial.relative_to(ROOT)} and docs/assets/hero-pulse.css "
          f"({len(paths)} pulses)")


if __name__ == "__main__":
    main()
